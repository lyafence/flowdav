func FuzzEnvelopeUnmarshalBinary(f *testing.F) {
	f.Add([]byte{0x1F, 0x01, 0x00, 0x05, 0x68, 0x65, 0x6C, 0x6C, 0x6F, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x42, 0x00, 0x00, 0x00, 0x00, 0x00})
	f.Fuzz(func(t *testing.T, data []byte) {
		var env Envelope
		_, err := env.UnmarshalBinary(data)
		if err != nil {
			return
		}
	})
}

